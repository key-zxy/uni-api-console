// Run with NODE_PATH pointing at the isolated jsdom test installation.
const assert = require('node:assert/strict');
const fs = require('node:fs');
const {JSDOM} = require('jsdom');
const data = {providers:[{provider:'one',base_url:'https://one.example/v1',models:[{source:'alias'},'shared']},{provider:'two',base_url:'https://two.example/v1',models:['shared']}],pools:{work:['one/alias'],other:['two/shared']},clients:[{name:'laptop',pool:'work',masked:'sk-abc****wxyz'}],external_clients:[{role:'user',label:'user',masked:'sk-zzz****9999',models:['one/alias'],bound_pool:'work',admin:false,copyable:true}]};
function boot() {
  const dom=new JSDOM(fs.readFileSync('index.html','utf8'),{url:'http://console.test/',runScripts:'outside-only'});
  const w=dom.window, calls=[];
  w.HTMLDialogElement.prototype.showModal=function(){this.open=true};
  w.HTMLDialogElement.prototype.close=function(){this.open=false;this.dispatchEvent(new w.Event('close'))};
  w.confirm=()=>true;
  w.fetch=async(url,options={})=>{calls.push({url,body:options.body?JSON.parse(options.body):null});return {ok:true,status:200,json:async()=>structuredClone(data)}};
  require('node:vm').runInContext(fs.readFileSync('app.js','utf8'),dom.getInternalVMContext()); w.testData=structuredClone(data);
  return {w,calls,dom};
}
(async()=>{
  const {w,calls,dom}=boot();
  await w.eval('managementRefresh()');
  assert.match(w.document.querySelector('#key-list').textContent,/laptop/,'use actual clients.name, not absent role');
  assert.match(w.document.querySelector('#key-list').textContent,/work/);
  assert.equal(w.document.querySelector('#key-list').textContent.includes('复制'),false,'saved key list must not pretend it has secret');
  assert.match(w.document.querySelector('#key-list').textContent,/sk-abc\*\*\*\*wxyz/,'masked key comes from the server, not the client name');
  assert.match(w.document.querySelector('#key-list').textContent,/已绑定模型池/,'native key shows its bound pool');
  w.eval('renderManagement(testData)'); w.eval('renderManagement(testData)');
  assert.equal(w.document.querySelectorAll('#pool-choices input').length,3,'polling must not duplicate choices');
  const edit=[...w.document.querySelectorAll('#key-list button')].find(b=>b.textContent==='编辑模型池');
  assert.ok(edit,'edit action still rendered');
  edit.click();
  assert.equal(w.document.querySelector('#client-dialog').open,true);
  assert.equal(w.document.querySelector('#client-name').value,'laptop');
  assert.equal(w.document.querySelector('#client-name').readOnly,true);
  w.document.querySelector('#client-pool').value='other';
  await w.document.querySelector('#client-form').onsubmit({preventDefault(){}});
  assert.deepEqual(calls.find(c=>c.body?.action==='client_update').body,{action:'client_update',name:'laptop',pool:'other'});
  assert.equal(w.document.querySelector('#client-dialog').open,false);
  const detail=w.document.querySelector('#provider-list details');
  assert.ok(detail,'provider models are expandable lists');
  detail.open=true;
  w.eval('renderManagement(testData)');
  assert.equal(w.document.querySelector('#provider-list details').open,true,'poll preserves expansion');
  const poolEdit=w.document.querySelector('#pool-list button'); poolEdit.click();
  assert.equal(w.document.querySelector('#pool-dialog').open,true);
  assert.equal(w.document.querySelector('#pool-name').value,'work');
  assert.equal(w.document.querySelector('#pool-name').readOnly,true);
  assert.deepEqual([...w.document.querySelectorAll('#pool-choices input:checked')].map(x=>x.value),['one/alias']);
  w.document.querySelector('#pool-search').value='shared';
  w.document.querySelector('#pool-search').dispatchEvent(new w.Event('input'));
  assert.equal(w.document.querySelector('#pool-choices input:checked').checked,true,'search does not erase hidden selection');
  w.auditRows=[{id:1,started:1,path:'/v1/chat/completions',client_name:'<img src=x onerror=alert(1)>',client_pool:'work',model:'shared',status:200,complete:1,prompt_tokens:10,completion_tokens:2,cached_tokens:0,duration:1}];
  w.fetch=async()=>({ok:true,status:200,json:async()=>w.auditRows});
  await w.eval('refresh()');
  assert.equal(w.document.querySelector('#rows img'),null,'API-controlled text must not become HTML');
  assert.match(w.document.querySelector('#rows').textContent,/200/,'keep exact HTTP status');
  assert.equal(w.document.querySelector('#rows .model-cell .p-tag')?.textContent,'渠道待确认','same model in two channels must not pick last provider');
  w.document.querySelector('#pool-dialog').close();
  w.eval('openClient(testData.clients[0])');
  w.fetch=async()=>({ok:false,status:409,json:async()=>({error:'测试：配置已变化'})});
  const form=w.document.querySelector('#client-form');
  await form.onsubmit({preventDefault(){},currentTarget:form});
  assert.equal(w.document.querySelector('#client-dialog').open,true,'failed edit remains open');
  assert.match(form.querySelector('.form-message').textContent,/配置已变化/,'error visible inside modal');
  w.eval('logout()');
  assert.equal(w.document.querySelectorAll('#key-list > *').length,0);
  assert.equal(w.document.querySelector('#client-key').textContent,'');
  dom.window.close();
  console.log('Real DOM: edit dialogs, expansion, selection, escaped records, modal errors and logout pass');
})().catch(e=>{console.error(e);process.exitCode=1});
